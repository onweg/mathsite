"""Чистая функция сборки RAG-промпта."""

from .chunk import SearchHit


def build_rag_prompt(query: str, hits: list[SearchHit]) -> str:
    if not hits:
        return (
            "Фрагменты учебника не найдены. "
            "Сообщи, что поиск не нашёл подходящие фрагменты; "
            "не утверждай, что ответа нет в самом учебнике."
        )
    parts = [
        f"[{i}] (стр. {h.page}, {h.source}) {h.text}"
        for i, h in enumerate(hits, start=1)
    ]
    fragments = "\n\n".join(parts)
    return (
        "Ответь ученику 8 класса СТРОГО на основе фрагментов учебника ниже. "
        "Не придумывай факты, которых нет во фрагментах. "
        "Если во фрагментах нет ответа — скажи, что найденных фрагментов "
        "недостаточно для ответа. Не утверждай, что темы нет в самом учебнике. "
        "Если формулы повреждены при извлечении (например, содержат /mat7), "
        "не угадывай утраченные символы; объясни ограничение и предложи "
        "свериться с указанной страницей PDF. В конце ответа укажи номера фрагментов, которые ты "
        "использовал, в формате [1][2].\n\n"
        f"ФРАГМЕНТЫ:\n{fragments}\n\n"
        f"ВОПРОС УЧЕНИКА: {query}"
    )
