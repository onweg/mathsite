_NORMALIZE_RE = re.compile(r"[^а-яёa-z0-9\s]+")
_SPACES_RE = re.compile(r"\s+")


def normalize(s: str) -> str:
    s = s.lower()
    s = _NORMALIZE_RE.sub(" ", s)
    s = _SPACES_RE.sub(" ", s).strip()
    return s
