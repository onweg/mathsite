import { test, expect, login, installExternalFixtures } from './fixtures'

test('battle round: student publication, peer and AI reviews, likes and frozen winners', async ({ page, pupil, teacherApi, browser, baseURL, viewport, isMobile, hasTouch, deviceScaleFactor }) => {
  test.setTimeout(100_000)
  page.on('dialog', dialog => dialog.accept())
  pupil.on('dialog', dialog => dialog.accept())
  await login(page)
  await page.getByRole('button', { name: 'Математический батл', exact: true }).click()
  await page.getByRole('button', { name: 'Создать раунд', exact: true }).click()
  await page.getByLabel('Название раунда', { exact: true }).fill('Ремонт без лишних расходов')
  await page.getByLabel('Тема и правила', { exact: true }).fill('Быт')
  await page.getByRole('button', { name: 'Сохранить раунд', exact: true }).click()
  await page.getByRole('button', { name: 'Запустить батл', exact: true }).click()
  await expect(page.getByText('Идёт батл', { exact: true })).toBeVisible()
  const [round] = await (await teacherApi.get('/admin/battles')).json()
  await pupil.goto('/#battles')
  const authorSection = pupil.getByRole('region', { name: 'Математический батл', exact: true })
  await authorSection.getByRole('button').filter({ hasText: 'Ремонт без лишних расходов' }).click()
  await authorSection.getByRole('tab', { name: 'Моё участие', exact: true }).click()
  await authorSection.getByLabel('Название задачи', { exact: true }).fill('Сколько купить краски')
  await authorSection.getByLabel('Условие задачи', { exact: true }).fill('Стена 20 м², два слоя краски. Литра хватает на 10 м². Сколько литров нужно?')
  await authorSection.getByLabel('Где пригодится в жизни', { exact: true }).fill('Чтобы купить нужное количество краски.')
  await authorSection.getByLabel('Эталонное решение и ответ', { exact: true }).fill('20 × 2 / 10 = 4 литра краски.')
  await authorSection.getByRole('button', { name: 'Сохранить задачу', exact: true }).click()
  await authorSection.getByRole('button', { name: 'На проверку учителю', exact: true }).click()
  await expect(authorSection.getByText('На проверке учителя', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Обновить', exact: true }).click()
  await page.getByText('Эталонное решение', { exact: true }).click()
  await expect(page.getByText('20 × 2 / 10 = 4 литра краски.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Одобрить и опубликовать', exact: true }).click()
  await expect(page.getByText('Опубликована', { exact: true })).toBeVisible()

  const created = await teacherApi.post('/admin/students', { data: { name: 'Мария Решатель', class_label: '9А' } })
  const solverStudent = await created.json()
  const context = await browser.newContext({ baseURL, viewport, isMobile, hasTouch, deviceScaleFactor, reducedMotion: 'reduce' })
  await installExternalFixtures(context)
  const solver = await context.newPage()
  const errors: string[] = []
  solver.on('pageerror', e => errors.push(e.message))
  solver.on('dialog', d => d.accept())
  try {
    await solver.goto(`/s/${solverStudent.qr_token}`)
    await expect(solver).toHaveURL(/\/me$/)
    await solver.goto('/#battles')
    const section = solver.getByRole('region', { name: 'Математический батл', exact: true })
    await section.getByRole('button').filter({ hasText: 'Ремонт без лишних расходов' }).click()
    await expect(section.getByText('Эталонное решение', { exact: true })).toHaveCount(0)
    await section.getByRole('button', { name: 'Поставить лайк', exact: true }).click()
    await expect(section.getByRole('button', { name: 'Снять лайк', exact: true })).toBeVisible()
    await section.getByRole('button', { name: 'Решить задачу', exact: true }).click()
    await section.getByLabel('Моё решение', { exact: true }).fill('Для двух слоёв нужно покрыть 40 м²: 40 / 10 = 4 литра краски.')
    await section.getByRole('button', { name: 'Отправить решение', exact: true }).click()
    await section.getByRole('tab', { name: 'Моё участие', exact: true }).click()
    await expect(section.getByText(/Проверено нейросетью/)).toBeVisible({ timeout: 20_000 })

    await page.getByRole('button', { name: 'Обновить', exact: true }).click()
    await page.getByRole('tab', { name: 'Проверка работ', exact: true }).click()
    await page.getByRole('button', { name: 'Оценка учителя', exact: true }).click()
    await page.getByLabel('Рассуждения (0–4)', { exact: true }).fill('3')
    await page.getByLabel('Вычисления и ответ (0–4)', { exact: true }).fill('4')
    await page.getByLabel('Жизненный контекст (0–2)', { exact: true }).fill('2')
    await page.getByLabel('Обратная связь', { exact: true }).fill('Расчёт верный, подробнее объясни площадь двух слоёв.')
    await page.getByRole('button', { name: 'Сохранить оценку', exact: true }).click()

    await authorSection.getByRole('button', { name: 'Обновить', exact: true }).click()
    await authorSection.getByRole('tab', { name: 'Я проверяю', exact: true }).click()
    await expect(authorSection.getByText('Мария Решатель')).toHaveCount(0)
    await authorSection.getByRole('button', { name: 'Оценка автора', exact: true }).click()
    await authorSection.getByLabel('Рассуждения (0–4)', { exact: true }).fill('2')
    await authorSection.getByLabel('Вычисления и ответ (0–4)', { exact: true }).fill('4')
    await authorSection.getByLabel('Жизненный контекст (0–2)', { exact: true }).fill('2')
    await authorSection.getByLabel('Обратная связь', { exact: true }).fill('Верно, но можно подробнее объяснить формулу.')
    await authorSection.getByRole('button', { name: 'Сохранить оценку', exact: true }).click()
    await expect(authorSection.getByText('Итог: 9 / 10', { exact: true })).toBeVisible()

    await page.getByRole('button', { name: 'Завершить приём работ', exact: true }).click()
    await page.getByRole('button', { name: 'Подвести итоги', exact: true }).click()
    await page.getByRole('tab', { name: 'Итоги и рейтинг', exact: true }).click()
    await expect(page.getByText('Лидер: Мария Решатель', { exact: true })).toBeVisible()
    await expect(page.getByText('Лидер: Иван Браузерный', { exact: true })).toBeVisible()
    await section.getByRole('button', { name: 'Обновить', exact: true }).click()
    await section.getByRole('tab', { name: 'Итоги и рейтинг', exact: true }).click()
    await expect(section.getByRole('cell', { name: /Мария Решатель · это ты/ })).toBeVisible()
    expect(await solver.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await solver.screenshot({ path: test.info().outputPath('battle-ranking.png') })
    await solver.reload()
    await section.getByRole('button').filter({ hasText: 'Ремонт без лишних расходов' }).click()
    await section.getByRole('tab', { name: 'Итоги и рейтинг', exact: true }).click()
    await expect(section.getByText('Лидер: Мария Решатель', { exact: true })).toBeVisible()
    const final = await (await teacherApi.get(`/admin/battles/${round.id}`)).json()
    expect(final.round.status).toBe('closed')
    expect(final.rankings.solvers[0].score).toBe(9)
    await page.getByRole('button', { name: 'Снять с публикации', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Опубликовать снова', exact: true })).toBeVisible()
    await section.getByRole('button', { name: 'Обновить', exact: true }).click()
    await expect(section.getByRole('alert')).toHaveText('Раунд снят с публикации')
    await expect(section.getByText('Лидер: Мария Решатель', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Опубликовать снова', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Снять с публикации', exact: true })).toBeVisible()
    await section.getByRole('button', { name: 'К раундам', exact: true }).click()
    await section.getByRole('button').filter({ hasText: 'Ремонт без лишних расходов' }).click()
    await section.getByRole('tab', { name: 'Итоги и рейтинг', exact: true }).click()
    await expect(section.getByText('Лидер: Мария Решатель', { exact: true })).toBeVisible()
    page.removeAllListeners('dialog')
    page.once('dialog', dialog => dialog.dismiss())
    await page.getByRole('button', { name: 'Удалить раунд', exact: true }).click()
    expect((await teacherApi.get(`/admin/battles/${round.id}`)).status()).toBe(200)
    page.once('dialog', async dialog => {
      expect(dialog.message()).toContain('Ремонт без лишних расходов')
      await dialog.accept()
    })
    await page.getByRole('button', { name: 'Удалить раунд', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Создать раунд', exact: true })).toBeVisible()
    await expect(page.getByRole('button').filter({ hasText: 'Ремонт без лишних расходов' })).toHaveCount(0)
    expect((await teacherApi.get(`/admin/battles/${round.id}`)).status()).toBe(404)
    expect(errors).toEqual([])
  } finally { await context.close() }
})
