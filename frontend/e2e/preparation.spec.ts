import { test, expect, login, createQuiz, API } from './fixtures'

for (const [track, grade, exam] of [['oge', '9А', 'ОГЭ'], ['ege', '11Б', 'ЕГЭ']] as const) {
  test(`library ${exam}: teacher creates practice, QR pupil retries, guests and other grades cannot access`, async ({ page, pupil, teacherApi }, testInfo) => {
    const common = await createQuiz(teacherApi)
    const weekly = await (await teacherApi.post('/admin/weekly', { data: { title: 'Общая задача', body_md: 'Решите уравнение', answer_md: 'Ответ' } })).json()
    expect((await teacherApi.post(`/admin/weekly/${weekly.id}/publish`)).ok()).toBeTruthy()
    const resource = await (await teacherApi.post('/admin/library', { data: { collection: track, kind: 'link', title: 'Полезный ресурс', url: 'https://example.org/math' } })).json()
    expect((await teacherApi.post(`/admin/library/${resource.id}/publish`)).ok()).toBeTruthy()
    await login(page)
    await page.getByRole('button', { name: 'Разделы', exact: true }).click()
    await page.getByRole('button', { name: new RegExp(`Подготовка к ${exam}`) }).click()
    await page.getByRole('button', { name: `Управлять тестами ${exam}`, exact: true }).click()
    await page.getByRole('button', { name: /свой тест/ }).click()
    await page.getByPlaceholder('Например: Квадратные уравнения · проверка').fill(`Тренировка ${exam}`)
    await page.getByRole('button', { name: 'создать и перейти к вопросам' }).click()
    await page.getByRole('button', { name: 'править', exact: true }).click()
    const editor = page.getByText('редактирование № 1', { exact: true }).locator('..')
    await editor.locator('textarea').first().fill('Сколько будет 2 + 2?')
    await editor.locator('input').nth(1).fill('Четыре')
    await editor.locator('input').nth(3).fill('Пять')
    await editor.getByRole('button', { name: 'сохранить', exact: true }).click()
    await page.getByRole('button', { name: 'опубликовать', exact: true }).click()
    await expect(page.getByRole('button', { name: 'снять с публикации' })).toBeVisible()
    const [quiz] = await (await teacherApi.get(`/admin/quizzes?track=${track}`)).json()
    expect(quiz.track).toBe(track)
    expect((await (await teacherApi.get('/admin/quizzes')).json()).map((q: { id: string }) => q.id)).toEqual([common.id])

    // A teacher login is not a pupil QR login: no private quiz data for this browser.
    await page.goto(`/library/${track}`)
    await expect(page.getByText(`Тренировка ${exam}`, { exact: true })).toHaveCount(0)
    await expect(page.getByRole('link', { name: 'Как войти по QR' })).toBeVisible()
    await expect(page.getByRole('link', { name: /Полезный ресурс/ })).toBeVisible()
    expect((await page.request.get(`${API}/quizzes/${quiz.id}`)).status()).toBe(404)
    await expect(page.locator('#quizzes').getByRole('button', { name: /Проверка сложения/ })).toBeVisible()
    await expect(page.locator('#weekly').getByText('Общая задача', { exact: true })).toBeVisible()

    // The original pupil is in 8A and cannot open the exam quiz either.
    await pupil.goto(`/library/${track}`)
    await expect(pupil.getByText(/В твоём профиле указан класс/)).toBeVisible()
    expect((await pupil.request.get(`${API}/quizzes/${quiz.id}`)).status()).toBe(404)
    const student = await (await teacherApi.post('/admin/students', { data: { name: `Ученик ${exam}`, class_label: grade } })).json()
    await pupil.goto(`/s/${student.qr_token}`)
    await expect(pupil).toHaveURL(/\/me$/)
    await pupil.getByRole('link', { name: /Тесты для подготовки/ }).click()
    await expect(pupil).toHaveURL(new RegExp(`/library/${track}$`))
    const practice = pupil.getByRole('region', { name: 'Тесты для прохождения', exact: true })
    await expect(practice.getByRole('button', { name: new RegExp(`Тренировка ${exam}`) })).toBeVisible()
    await expect(pupil.getByRole('link', { name: /Полезный ресурс/ })).toBeVisible()
    await expect(pupil.locator('#quizzes').getByRole('button', { name: /Проверка сложения/ })).toBeVisible()
    expect(await pupil.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await expect(pupil.getByText('Загрузка · Mathematica', { exact: true })).toHaveCount(0)
    await practice.getByRole('list').scrollIntoViewIfNeeded()
    await expect(practice.getByRole('list').locator('..')).toHaveCSS('opacity', '1')
    await practice.screenshot({ path: testInfo.outputPath('preparation.png') })

    for (const answer of ['Пять', 'Четыре']) {
      await practice.getByRole('button', { name: new RegExp(`Тренировка ${exam}`) }).click()
      await practice.getByRole('button', { name: new RegExp(answer) }).click()
      await practice.getByRole('button', { name: 'проверить', exact: true }).click()
      await expect(practice.getByText(answer === 'Пять' ? '0%' : '100%', { exact: true })).toBeVisible()
      await practice.getByRole('button', { name: 'к списку тестов' }).click()
      await expect(practice.getByText('Пройти ещё раз →', { exact: true })).toBeVisible()
    }
    await practice.getByRole('button', { name: 'Не пройдены', exact: true }).click()
    await expect(practice.getByText(/Нет тестов с выбранным статусом/)).toBeVisible()
    await practice.getByRole('button', { name: 'Пройдены', exact: true }).click()
    await expect(practice.getByRole('button', { name: new RegExp(`Тренировка ${exam}`) })).toBeVisible()
    const summary = await (await teacherApi.get(`/admin/quizzes/${quiz.id}/attempts/summary`)).json()
    expect(summary.students[0].attempts_count).toBe(2)
    await practice.getByRole('link', { name: 'Мои результаты', exact: true }).click()
    await expect(pupil.getByText(`Тренировка ${exam}`, { exact: true })).toHaveCount(2)
    await pupil.getByRole('button', { name: 'выйти', exact: true }).click()
    await pupil.goto(`/library/${track}`)
    await expect(pupil.getByText(`Тренировка ${exam}`, { exact: true })).toHaveCount(0)
    await expect(pupil.getByRole('link', { name: 'Как войти по QR' })).toBeVisible()
  })
}
