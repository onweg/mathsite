import { test, expect, login, API } from './fixtures'

test('solution exercise generation, publication, AI feedback, history and teacher correction', async ({ page, pupil, teacherApi }) => {
  await login(page)
  await page.getByRole('button', { name: 'Проверь решение', exact: true }).click()
  await page.getByRole('button', { name: 'Сгенерировать задание', exact: true }).click()
  await page.getByLabel('Тема задания', { exact: true }).fill('Раскрытие скобок')
  await page.getByRole('button', { name: 'Создать черновик с нейросетью' }).click()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Проверь раскрытие скобок')
  await expect(page.getByRole('button', { name: 'Опубликовать задание', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Предпросмотр задания' }).click()
  await expect(page.locator('.math-rich').getByText('Решите уравнение 2(x − 3) = 8.', { exact: true })).toBeVisible()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Опубликовать задание', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Снять с публикации', exact: true })).toBeVisible()
  const [task] = await (await teacherApi.get('/admin/solution-checks')).json()
  const correct = task.solutions.find((s: { is_correct: boolean }) => s.is_correct)
  await pupil.goto('/#solution-checks')
  const section = pupil.getByRole('region', { name: 'Проверь решение', exact: true })
  await section.getByRole('button', { name: 'Открыть задание', exact: true }).click()
  await expect(section.getByRole('radio')).toHaveCount(4)
  const publicTask = await (await pupil.request.get(`${API}/solution-checks/${task.id}`)).json()
  expect(JSON.stringify(publicTask)).not.toContain('is_correct')
  expect(JSON.stringify(publicTask)).not.toContain('PRIVATE-RUBRIC')
  const card = section.locator('fieldset > div').filter({ hasText: correct.body_md })
  await card.getByRole('radio').focus()
  await pupil.keyboard.press('Space')
  await expect(section.getByRole('textbox')).toHaveCount(3)
  for (const input of await section.getByRole('textbox').all()) await input.fill('Ошибка в преобразовании: нужно проверить знак и выполнить действие правильно.')
  pupil.once('dialog', d => d.accept())
  await section.getByRole('button', { name: 'Отправить на проверку' }).click()
  await expect(section.getByRole('status')).toHaveText('Проверено нейросетью', { timeout: 20_000 })
  await expect(section.getByText('7 / 7', { exact: true })).toBeVisible()
  await expect(section.getByText('Ошибка найдена и объяснена.', { exact: true })).toHaveCount(3)
  await section.getByRole('link', { name: 'Моя история' }).click()
  await expect(pupil.getByText('Проверено нейросетью', { exact: true })).toBeVisible()
  await pupil.getByRole('button', { name: 'Мои ответы и обратная связь' }).click()
  await expect(pupil.getByText('Ошибка найдена и объяснена.', { exact: true })).toHaveCount(3)
  await page.getByRole('button', { name: 'Обновить ответы' }).click()
  await expect(page.getByText('Иван Браузерный · 8А', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Оценить вручную' }).click()
  await page.getByLabel('Баллы учителя (0–7)').fill('5')
  await page.getByLabel('Комментарий учителя').fill('Уточни, на каком шаге меняется знак.')
  await page.getByRole('button', { name: 'Сохранить оценку учителя' }).click()
  await expect(page.getByText('Проверено учителем', { exact: true })).toBeVisible()
  await pupil.reload()
  await expect(pupil.getByText('Проверено учителем', { exact: true })).toBeVisible()
  await expect(pupil.getByText('5 / 7', { exact: true })).toBeVisible()
  await expect(pupil.getByText('Уточни, на каком шаге меняется знак.', { exact: true })).toBeVisible()
  expect(await pupil.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Снять с публикации', exact: true }).click()
  expect(await (await pupil.request.get(`${API}/solution-checks`)).json()).toEqual([])
  await pupil.reload()
  await expect(pupil.getByText('5 / 7', { exact: true })).toBeVisible()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Опубликовать задание', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Снять с публикации', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить задание', exact: true }).click()
  await page.getByLabel('Для удаления введите название задания', { exact: true }).fill('Неверное название')
  await expect(page.getByRole('button', { name: 'Удалить безвозвратно', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Удалить безвозвратно', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Удалить задание', exact: true }).click()
  await page.getByLabel('Для удаления введите название задания', { exact: true }).fill(task.title)
  await page.getByRole('button', { name: 'Удалить безвозвратно', exact: true }).click()
  await expect(page.getByText('Пока нет заданий.', { exact: true })).toBeVisible()
  expect(await (await pupil.request.get(`${API}/solution-checks/me`)).json()).toEqual([])
})
